#  MATCHED-SCALE DISTANCE FUNCTIONS & SYMMETRIC HARD-BC PINN

def domain_distances(xy):
    X = xy[:, 0:1]
    Y = xy[:, 1:2]
    d_cold = torch.tanh(40.0 * X) * torch.tanh(40.0 * (1.0 - X))
    d_outer = d_cold * torch.tanh(40.0 * Y) * torch.tanh(40.0 * (1.0 - Y))

    dx = torch.relu(XL - X) + torch.relu(X - XR)
    dy = torch.relu(Y - ZETA)
    d_strip = torch.tanh(100.0 * torch.sqrt(dx * dx + dy * dy + 1e-16))
    return d_cold, d_strip, d_outer * d_strip


class MultiScaleFourierFeatures(nn.Module):
    def __init__(self, in_dim=2, num_freqs_low=12, num_freqs_high=10, sigma_low=2.0, sigma_high=12.0):
        super().__init__()
        B_low = torch.randn(in_dim, num_freqs_low) * sigma_low
        B_low[:, :4] = torch.tensor([[1.0, 0.0, 2.0, 0.0],
                                     [0.0, 1.0, 0.0, 2.0]])
        B_high = torch.randn(in_dim, num_freqs_high) * sigma_high
        self.register_buffer("B_low", B_low)
        self.register_buffer("B_high", B_high)
        self.low_dim = 2 + 2 * num_freqs_low
        self.high_dim = 2 * num_freqs_high

    def forward(self, xy):
        p_low = 2.0 * math.pi * (xy @ self.B_low)
        p_high = 2.0 * math.pi * (xy @ self.B_high)
        return torch.cat([
            xy,
            torch.sin(p_low), torch.cos(p_low),
            torch.sin(p_high), torch.cos(p_high),
        ], dim=-1)


class ModifiedMLP(nn.Module):
    def __init__(self, in_dim, low_dim, hidden_dim, out_dim, num_layers=4):
        super().__init__()
        self.encoder_u = nn.Sequential(nn.Linear(in_dim, hidden_dim), nn.Tanh())
        self.encoder_v = nn.Sequential(nn.Linear(in_dim, hidden_dim), nn.Tanh())
        self.in_layer = nn.Sequential(nn.Linear(in_dim, hidden_dim), nn.Tanh())
        self.hidden = nn.ModuleList([
            nn.Linear(hidden_dim, hidden_dim) for _ in range(num_layers - 1)
        ])
        self.out_layer = nn.Linear(hidden_dim, out_dim)

        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_normal_(m.weight)
                nn.init.zeros_(m.bias)

        for first_lin in [self.encoder_u[0], self.encoder_v[0], self.in_layer[0]]:
            with torch.no_grad():
                first_lin.weight[:, low_dim:] *= 0.05

    def forward(self, x):
        u = self.encoder_u(x)
        v = self.encoder_v(x)
        h = self.in_layer(x)
        for layer in self.hidden:
            z = torch.tanh(layer(h))
            h = (1.0 - z) * u + z * v
        return self.out_layer(h)


class SymmetricHardBCPINN(nn.Module):
    def __init__(self, hidden_dim=96):
        super().__init__()
        self.ff = MultiScaleFourierFeatures(in_dim=2, num_freqs_low=12, num_freqs_high=10, sigma_low=2.0, sigma_high=12.0)
        feat_dim = self.ff.low_dim + self.ff.high_dim
        self.flow_net = ModifiedMLP(feat_dim, self.ff.low_dim, hidden_dim, out_dim=2, num_layers=4)
        self.thermal_net = ModifiedMLP(feat_dim, self.ff.low_dim, hidden_dim, out_dim=1, num_layers=4)

    def forward(self, xy, current_ra):
        if not xy.requires_grad:
            xy = xy.detach().clone().requires_grad_(True)

        # Exact X = 0.5 mirror pair
        xy_sym = torch.cat([1.0 - xy[:, 0:1], xy[:, 1:2]], dim=1)

        feats = self.ff(xy)
        feats_sym = self.ff(xy_sym)

        flow_raw = self.flow_net(feats)
        flow_sym = self.flow_net(feats_sym)

        theta_raw = self.thermal_net(feats)
        theta_sym = self.thermal_net(feats_sym)

        # Odd parity for streamfunction psi(X,Y) = -psi(1-X,Y); even parity for P & Theta
        psi_hat = 0.5 * (flow_raw[:, 0:1] - flow_sym[:, 0:1])
        p_hat = 0.5 * (flow_raw[:, 1:2] + flow_sym[:, 1:2])
        theta_corr = 0.5 * (theta_raw[:, 0:1] + theta_sym[:, 0:1])

        d_cold, d_strip, D_vel = domain_distances(xy)
        psi_scale = 0.05 * math.sqrt(current_ra * PR)
        p_scale = current_ra * PR

        # Divergence-free, no-slip velocity
        psi = psi_scale * (D_vel ** 2) * psi_hat
        dpsi = torch.autograd.grad(psi.sum(), xy, create_graph=True, retain_graph=True)[0]
        U = dpsi[:, 1:2]
        V = -dpsi[:, 0:1]

        P = p_scale * p_hat

        # Matched-scale transfinite Dirichlet temperature lifting (Theta=0 cold, Theta=1 Pi-strip)
        base_theta = d_cold / (d_cold + d_strip + 1e-12)
        T = base_theta + (d_cold * d_strip) * theta_corr
        return U, V, P, T, psi, p_hat



#  COLLOCATION & VALIDATION SAMPLING

def grad(y, x):
    return torch.autograd.grad(y, x, torch.ones_like(y), create_graph=True, retain_graph=True)[0]


def filter_fluid(points):
    X, Y = points[:, 0], points[:, 1]
    in_solid = (X >= XL) & (X <= XR) & (Y >= 0.0) & (Y <= ZETA)
    return points[~in_solid]


def generate_interior(n_uniform=5500, n_walls=2500, n_strip_bl=3000):
    parts = []
    if n_uniform > 0:
        chunks, collected = [], 0
        while collected < n_uniform:
            pts = filter_fluid(torch.rand(max(4000, 2 * (n_uniform - collected)), 2, device=DEVICE, dtype=DTYPE))
            chunks.append(pts)
            collected += pts.shape[0]
        parts.append(torch.cat(chunks, dim=0)[:n_uniform])

    if n_walls > 0:
        w_chunks, w_collected = [], 0
        while w_collected < n_walls:
            u1 = torch.rand(max(3000, 2 * (n_walls - w_collected)), 2, device=DEVICE, dtype=DTYPE)
            pts = filter_fluid(0.5 * (1.0 - torch.cos(math.pi * u1)))
            w_chunks.append(pts)
            w_collected += pts.shape[0]
        parts.append(torch.cat(w_chunks, dim=0)[:n_walls])

    if n_strip_bl > 0:
        s_chunks, s_collected = [], 0
        while s_collected < n_strip_bl:
            m = max(2000, n_strip_bl - s_collected)
            d_bl = 1e-4 + 0.05 * (torch.rand(m, 1, device=DEVICE, dtype=DTYPE) ** 2)
            p_l = torch.cat([XL - d_bl, (ZETA + 0.05) * torch.rand(m, 1, device=DEVICE, dtype=DTYPE)], dim=1)
            p_r = torch.cat([XR + d_bl, (ZETA + 0.05) * torch.rand(m, 1, device=DEVICE, dtype=DTYPE)], dim=1)
            p_t = torch.cat([(XL - 0.05) + (EPSILON + 0.10) * torch.rand(m, 1, device=DEVICE, dtype=DTYPE), ZETA + d_bl], dim=1)
            pts = filter_fluid(torch.clamp(torch.cat([p_l, p_r, p_t], dim=0), 1e-5, 1.0 - 1e-5))
            s_chunks.append(pts)
            s_collected += pts.shape[0]
        parts.append(torch.cat(s_chunks, dim=0)[:n_strip_bl])

    return torch.cat(parts, dim=0)


def horizontal_clustered(y, x0, x1, count):
    u = torch.rand(count, 1, device=DEVICE, dtype=DTYPE)
    x = x0 + (x1 - x0) * 0.5 * (1.0 - torch.cos(math.pi * u))
    return torch.cat((x, torch.full_like(x, y)), dim=1)


